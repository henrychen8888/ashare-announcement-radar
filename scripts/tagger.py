def classify_topic(cols, title):
    """返回 (主题, 命中依据串)"""
    text = "|".join(cols) + "||" + title
    for topic, kws in TOPIC_RULES:
        for kw in kws:
            if kw in text:
                return topic, kw
    return "其他", ""


def _norm(s):
    return re.sub(r"\s+", "", s or "")


# ---------------------------------------------------------------- 否定语义
# 「未减持」「终止减持」「不减持」这类标题如果按「减持」打 -2，方向会整个反过来。
# 实测踩过：603600「董事、高管未减持公司股份并提前终止减持计划」被判 S 级利空。
NEGATIVE_OF_BEARISH = [
    # (标题特征词, 覆盖后分值, 说明)
    (["终止减持", "提前终止减持", "减持计划终止"], +2, "终止减持"),
    (["未减持", "不减持", "零减持", "未实施减持", "放弃减持", "无减持"], +1, "未减持"),
    (["终止回购", "回购方案终止", "不再回购"], -1, "终止回购"),
    (["终止收购", "收购终止", "重组终止", "终止重大资产"], -2, "终止收购"),
    # 不要写裸「终止」—— 会误伤「终止上市」这种重大利空
    (["撤回发行", "终止发行", "中止审查", "终止审查", "撤回申请"], -1, "撤回/终止审核"),
]

# 这些词出现在标题里，说明是「承诺/说明」类文件而非事件本身
NEUTRAL_GUARD = ["承诺", "说明", "声明", "澄清"]


def apply_negation(title_n):
    """返回 (score_override or None, reason)"""
    for kws, val, reason in NEGATIVE_OF_BEARISH:
        if any(k in title_n for k in kws):
            return val, reason
    return None, ""


def score_direction(cols, title):
    """
    返回 (score, hits) —— hits 为 [(来源, 词, 分值)]，全部可溯源
    """
    hits = []
    cols_n = [_norm(c) for c in cols]
    for val, kws in COLUMN_SCORE:
        for kw in kws:
            for c in cols_n:
                if kw in c:
                    hits.append(("column", c + "~" + kw, val))
    title_n = _norm(title)
    for val, kws in TITLE_SCORE:
        for kw in kws:
            if kw in title_n:
                hits.append(("title", kw, val))

    if not hits:
        return 0, []

    # 列名是结构化数据，权重更高：列名命中直接采纳其分值；
    # 标题只用来「修正」而不是「主导」—— 标题命中同号则 +1 追加强度，异号则衰减一半
    col_vals = [h[2] for h in hits if h[0] == "column"]
    ttl_vals = [h[2] for h in hits if h[0] == "title"]

    if col_vals:
        base = max(col_vals, key=abs)
        if ttl_vals:
            tmax = max(ttl_vals, key=abs)
            if (base > 0) == (tmax > 0):
                base = base + (1 if base > 0 else -1)
            else:
                base = base // 2
    else:
        base = max(ttl_vals, key=abs)

    return base, hits


def tag(ann):
    """
    ann: dict 至少含 columns(list[str]), title(str)
    返回 dict: topic / direction / score / level / hits / is_noise
    """
    cols = ann.get("columns") or []
    title = ann.get("title") or ""
    topic, topic_hit = classify_topic(cols, title)
    score, hits = score_direction(cols, title)

    # -------- 否定语义优先：覆盖方向
    title_n = _norm(title)
    neg_val, neg_reason = apply_negation(title_n)
    if neg_val is not None:
        score = neg_val
        hits = hits + [("negation", neg_reason, neg_val)]

    if score > 0:
        direction, dlabel = 1, "利好"
    elif score < 0:
        direction, dlabel = -1, "利空"
    else:
        direction, dlabel = 0, "中性"

    abs_s = min(abs(score), 3)

    # 定级：白名单优先，分数兜底
    cols_n2 = "|".join(cols)
    is_s = False
    if direction > 0:
        is_s = any(k in cols_n2 for k in S_UP_COLS) or any(k in title for k in S_UP_TITLE)
    elif direction < 0:
        is_s = any(k in cols_n2 for k in S_DOWN_COLS) or any(k in title for k in S_DOWN_TITLE)

    if direction != 0 and is_s:
        level = "S"
        abs_s = max(abs_s, 3)
    elif abs_s >= 2:
        level = "A"
    elif abs_s >= 1:
        level = "B"
    else:
        level = "N"

    # 文件型公告降级：方向保留，但不占「重大」席位
    is_doc = any(k in title for k in DOC_LIKE)
    if is_doc and level in ("S", "A"):
        level = "B" if direction != 0 else "N"

    return {
        "topic": topic,
        "topic_hit": topic_hit,
        "score": score,
        "direction": direction,
        "direction_label": dlabel,
        "level": level,
        "is_doc": is_doc,
        "hits": hits,
        # 噪音：中性 + 资金募集/公司治理主题
        "is_noise": (direction == 0 and topic in NOISE_TOPICS),
    }


